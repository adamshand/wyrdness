#!/usr/bin/env node

import { mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, resolve } from 'node:path';

const DEFAULT_WALK = 'tools/calibration/walk-distance-200bit-lookback120-1m.json';
const DEFAULT_STACK = 'tools/calibration/signal-stack-200bit-lookback120-1m.json';
const DEFAULT_OUT = 'app/public/calibration.js';
const MIN_SUPPORTED_TAIL = 0.0001;

function usage() {
	return (
		`Usage: node tools/generate-runtime-calibration.js [options]\n\n` +
		`Generates app/public/calibration.js from calibration JSON files so runtime\n` +
		`tables cannot drift from checked-in calibration reports.\n\n` +
		`Options:\n` +
		`  --walk <path>    Walk calibration JSON. Default: ${DEFAULT_WALK}\n` +
		`  --stack <path>   Full-stack calibration JSON. Default: ${DEFAULT_STACK}\n` +
		`  --out <path>     Runtime JS output. Default: ${DEFAULT_OUT}\n` +
		`  --help           Show this help\n`
	);
}

function parseArgs(argv) {
	const options = { walk: DEFAULT_WALK, stack: DEFAULT_STACK, out: DEFAULT_OUT };
	for (let i = 2; i < argv.length; i++) {
		const arg = argv[i];
		const next = () => {
			const value = argv[++i];
			if (value == null || value.startsWith('--')) throw new Error(`Missing value for ${arg}`);
			return value;
		};
		switch (arg) {
			case '--walk':
				options.walk = next();
				break;
			case '--stack':
				options.stack = next();
				break;
			case '--out':
				options.out = next();
				break;
			case '--help':
				console.log(usage());
				process.exit(0);
			default:
				throw new Error(`Unknown option: ${arg}`);
		}
	}
	return options;
}

function supportedTailRows(rows) {
	return rows.filter(([p, threshold]) => p >= MIN_SUPPORTED_TAIL && Number.isFinite(p) && Number.isFinite(threshold));
}

function lowerAscending(rows) {
	return supportedTailRows(rows).sort((a, b) => a[1] - b[1]);
}

function upperAscending(rows) {
	return supportedTailRows(rows).sort((a, b) => a[1] - b[1]);
}

function main() {
	const options = parseArgs(process.argv);
	const walk = JSON.parse(readFileSync(resolve(options.walk), 'utf8'));
	const stack = JSON.parse(readFileSync(resolve(options.stack), 'utf8'));
	const calibration = {
		version: 1,
		generatedAt: new Date().toISOString(),
		sources: {
			walk: options.walk,
			stack: options.stack
		},
		params: {
			sampleBits: stack.params.sampleBits,
			maxLookback: stack.params.maxLookback,
			minSegmentLen: stack.params.minSegmentLen,
			recordedSamples: stack.params.recordedSamples,
			minSupportedTail: MIN_SUPPORTED_TAIL,
			note: 'Runtime lookup tables are capped at minSupportedTail; more extreme observations display as <= this supported tail, not as precise rarer probabilities.'
		},
		walkCloseLowerTail: lowerAscending(walk.walkDistance.closeRatio.lowerTailThresholds),
		walkSeparateUpperTail: upperAscending(walk.walkDistance.separateRatio.upperTailThresholds),
		corrHighUpperTail: upperAscending(stack.signal.corrHighZ.upperTailThresholds),
		corrLowUpperTail: upperAscending(stack.signal.corrLowZ.upperTailThresholds),
		antiAbUpperTail: upperAscending(stack.signal.antiAbZ.upperTailThresholds),
		antiBaUpperTail: upperAscending(stack.signal.antiBaZ.upperTailThresholds),
		pearsonAbsUpperTail: upperAscending(stack.signal.pearsonAbsZ.upperTailThresholds),
		fullStackPMinLowerTail: lowerAscending(stack.signal.pMinRaw.lowerTailThresholds)
	};

	const content =
		`// Generated by tools/generate-runtime-calibration.js. Do not edit by hand.\n` +
		`(function (root) {\n` +
		`    'use strict';\n` +
		`    root.WyrdCalibration = ${JSON.stringify(calibration, null, 4)};\n` +
		`})(typeof globalThis !== 'undefined' ? globalThis : this);\n`;
	const outPath = resolve(options.out);
	mkdirSync(dirname(outPath), { recursive: true });
	writeFileSync(outPath, content);
	console.log(`Wrote ${outPath}`);
}

try {
	main();
} catch (error) {
	console.error(error instanceof Error ? error.message : error);
	console.error('\n' + usage());
	process.exit(1);
}
